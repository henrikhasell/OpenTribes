// HH: Added for Tribes 2 compatibility.
/// @file
/// Which node of a datablock's layout is which field.
///
/// The datablock tables came out of the walk as anonymous node arrays,
/// so a class reading one can only recognise a field by its shape --
/// and a datablock body is mostly machine words and eleven-bit
/// references, which by shape are one field repeated.  A run of them
/// with a hole in it is indistinguishable from a shorter run, so a
/// class either files the lot or files none.  These names are what let
/// it file one.
///
/// Written by Tools/t2/gendatablocknames.py, which reads the committed
/// table rather than rewriting it: the bits are already right and
/// already agree with the second reader, and nothing here may move
/// them.  A field list that no longer matches the graph it describes
/// stops that script instead of landing a wrong name here.

