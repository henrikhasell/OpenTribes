// HH: Added for Tribes 2 compatibility.
/// @file
/// Which node of a layout is which field, for the layouts written out by
/// hand in Tools/t2/handlayout.py.
///
/// A field's op and width are the better handle and survive a
/// regeneration, but they cannot tell two optional fields of the same
/// shape apart: a ShapeBase body is four sound slots, four thread slots
/// and eight image slots, and which slot a value belongs to is the whole
/// of the information.  T2Reader::node() gives the cursor's node and
/// these say what it means, so a reader names a field rather than
/// counting arrivals and hoping.
///
/// Written by Tools/t2/genghost.py; see Tools/t2/README.md.

